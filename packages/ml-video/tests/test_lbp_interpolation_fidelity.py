def test_reference_is_reproducible_from_notebook_port():
    """The committed golden is exactly what the notebook port yields on the
    frozen synthetic input — ties the constant to a reproducible source."""
    frames, landmarks = _synthetic_frames_and_landmarks()
    assert np.allclose(_nb_lbptop(frames, landmarks), NOTEBOOK_LBP_REFERENCE, atol=1e-12)


def test_lbp_top_matches_training_interpolation():
    """``lbp_top_features`` must reproduce the INTER_LINEAR (training) reference.

    FAILS if the ROI resize uses INTER_AREA (or any non-default filter): that
    shifts the 90-d block out of the trained feature space while still summing
    to 9.0, so only this value-level check catches it.
    """
    frames, landmarks = _synthetic_frames_and_landmarks()
    vec = F.lbp_top_features(frames, landmarks)
    assert vec.shape == (F.LBP_DIM,)
    assert np.allclose(vec, NOTEBOOK_LBP_REFERENCE, atol=1e-6)
